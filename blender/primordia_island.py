SUN_ELEVATION, SUN_AZIMUTH = 34.0, 300.0      # grados; azimut desde el norte en sentido horario


def set_optional(target, attribute, value):
    """Asigna solo si la propiedad existe en esta versión de Blender."""
    if hasattr(target, attribute):
        setattr(target, attribute, value)


def create_sun(collection):
    light = bpy.data.lights.new("PRIM_Sun", "SUN")
    light.energy, light.angle, light.color = 4.2, math.radians(1.5), (1.0, 0.93, 0.82)
    elevation, azimuth = math.radians(SUN_ELEVATION), math.radians(SUN_AZIMUTH)
    towards_sun = Vector((math.sin(azimuth) * math.cos(elevation),
                          math.cos(azimuth) * math.cos(elevation), math.sin(elevation)))
    sun = new_object("PRIM_Sun", light, collection, location=towards_sun * 80.0)
    sun.rotation_euler = (-towards_sun).to_track_quat("-Z", "Y").to_euler()
    return sun


def setup_world(scene):
    """Cielo físico para la iluminación ambiental; fondo de estudio oscuro para cámara."""
    world = bpy.data.worlds.get("PRIM_World") or bpy.data.worlds.new("PRIM_World")
    scene.world = world
    b = NodeBuilder(world)
    sky = b.new("ShaderNodeTexSky")
    sky_types = sky.bl_rna.properties["sky_type"].enum_items.keys()
    sky.sky_type = next(t for t in ("NISHITA", "MULTIPLE_SCATTERING", "SINGLE_SCATTERING", "HOSEK_WILKIE", "PREETHAM")
                        if t in sky_types)
    set_optional(sky, "sun_disc", False)
    set_optional(sky, "sun_elevation", math.radians(SUN_ELEVATION))
    set_optional(sky, "sun_rotation", math.radians(SUN_AZIMUTH))
    set_optional(sky, "altitude", 600.0)
    set_optional(sky, "dust_density", 1.4)
    ambient = b.set_inputs(b.new("ShaderNodeBackground"), {"Color": sky.outputs["Color"], "Strength": 0.35})

    window = b.new("ShaderNodeSeparateXYZ")
    b.feed(window.inputs[0], b.new("ShaderNodeTexCoord").outputs["Window"])
    backdrop_color = b.ramp(window.outputs["Y"], [(0.0, "pedestal"), (1.0, "obelisk_metal")])
    backdrop = b.set_inputs(b.new("ShaderNodeBackground"), {"Color": backdrop_color, "Strength": 1.0})
    mix = b.new("ShaderNodeMixShader")
    b.feed(mix.inputs[0], b.new("ShaderNodeLightPath").outputs["Is Camera Ray"])
    b.feed(mix.inputs[1], ambient.outputs["Background"])
    b.feed(mix.inputs[2], backdrop.outputs["Background"])
    b.feed(b.new("ShaderNodeOutputWorld").inputs["Surface"], mix.outputs["Shader"])
    b.arrange()
    return world


def create_camera(name, collection, location, target=None, ortho_scale=None, lens=50.0):
    camera = bpy.data.cameras.new(name)
    camera.lens, camera.clip_start, camera.clip_end = lens, 0.5, 2000.0
    if ortho_scale:
        camera.type, camera.ortho_scale, camera.sensor_fit = "ORTHO", ortho_scale, "VERTICAL"
    obj = new_object(name, camera, collection, location=location)
    if target is not None:
        obj.rotation_euler = (Vector(target) - Vector(location)).to_track_quat("-Z", "Y").to_euler()
    return obj


def set_render_engine(scene, engine):
    candidates = {"EEVEE": ("BLENDER_EEVEE_NEXT", "BLENDER_EEVEE"), "CYCLES": ("CYCLES",)}[engine]
    for identifier in candidates:
        try:
            scene.render.engine = identifier
            return identifier
        except TypeError:
            continue
    raise RuntimeError(f"Motor de render no disponible: {engine}")


def configure_render(scene, engine):
    scene.render.resolution_x, scene.render.resolution_y = CFG.RESOLUTION
    scene.render.resolution_percentage = 100
    set_render_engine(scene, engine)
    eevee = scene.eevee
    for attribute, value in (("taa_render_samples", 64), ("use_raytracing", True), ("use_shadows", True),
                             ("use_gtao", True), ("use_bloom", True), ("shadow_cube_size", "2048")):
        set_optional(eevee, attribute, value)
    scene.cycles.samples = 96
    scene.cycles.use_denoising = True
    scene.view_settings.view_transform = "AgX"
    scene.view_settings.look = "AgX - Medium High Contrast"
    scene.view_settings.exposure = 0.0


def add_glow_compositing(scene):
    """Resplandor (bloom) de los obeliscos en el compositor.

    Blender 5.x usa un grupo de nodos asignado a la escena; 4.x, el árbol de la
    escena. Desde 4.4 los parámetros del Glare son sockets; antes, propiedades.
    """
    if hasattr(scene, "compositing_node_group"):
        tree = bpy.data.node_groups.new("PRIM_Compositor", "CompositorNodeTree")
        tree.interface.new_socket("Image", in_out="OUTPUT", socket_type="NodeSocketColor")
        output = tree.nodes.new("NodeGroupOutput")
        scene.compositing_node_group = tree
    else:
        scene.use_nodes = True
        tree = scene.node_tree
        tree.nodes.clear()
        output = tree.nodes.new("CompositorNodeComposite")
    layers = tree.nodes.new("CompositorNodeRLayers")
    glare = tree.nodes.new("CompositorNodeGlare")
    sockets = {"Type": "Fog Glow", "Quality": "High", "Threshold": 1.0, "Strength": 0.7}
    for name, value in sockets.items():
        if name in glare.inputs:
            glare.inputs[name].default_value = value
    set_optional(glare, "glare_type", "FOG_GLOW")
    set_optional(glare, "quality", "HIGH")
    if "Threshold" not in glare.inputs:
        glare.threshold, glare.mix, glare.size = 1.0, -0.3, 8
    tree.links.new(layers.outputs["Image"], glare.inputs["Image"])
    tree.links.new(glare.outputs["Image"], output.inputs[0])
    layers.location, glare.location, output.location = (-300, 0), (0, 0), (300, 0)


def configure_viewports():
    """En la interfaz: vista de cámara, Material Preview y recorte lejano adecuado."""
    for window in bpy.context.window_manager.windows:
        for area in window.screen.areas:
            if area.type != "VIEW_3D":
                continue
            for space in area.spaces:
                if space.type == "VIEW_3D":
                    space.clip_start, space.clip_end = 0.1, 2000.0
                    space.shading.type = "MATERIAL"
                    space.region_3d.view_perspective = "CAMERA"


