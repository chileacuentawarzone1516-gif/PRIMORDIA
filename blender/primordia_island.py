def spire_mesh(name, scale):
    """Obelisco estilizado: bipirámide de sección cuadrada con paneles emisivos."""
    bm = bmesh.new()
    profile = ((0.0, 0.0), (1.5, 0.42), (5.3, 0.52), (6.4, 0.30), (7.4, 0.0))
    angles = [math.pi / 4.0 + k * math.pi / 2.0 for k in range(4)]
    rings = []
    for z, radius in profile:
        if radius == 0.0:
            rings.append([bm.verts.new((0.0, 0.0, z * scale))])
        else:
            rings.append([bm.verts.new((radius * scale * math.cos(a), radius * scale * math.sin(a), z * scale))
                          for a in angles])
    bands = []
    for lower, upper in zip(rings, rings[1:]):
        faces = []
        for k in range(4):
            k1 = (k + 1) % 4
            if len(lower) == 1:
                faces.append(bm.faces.new((lower[0], upper[k1], upper[k])))
            elif len(upper) == 1:
                faces.append(bm.faces.new((lower[k], lower[k1], upper[0])))
            else:
                faces.append(bm.faces.new((lower[k], lower[k1], upper[k1], upper[k])))
        bands.append(faces)
    bmesh.ops.recalc_face_normals(bm, faces=bm.faces[:])
    glowing = bands[1] + bands[2]
    bmesh.ops.inset_individual(bm, faces=glowing, thickness=0.15 * scale, depth=-0.03 * scale)
    for face in glowing:
        face.material_index = 1
    mesh = bpy.data.meshes.new(name)
    bm.to_mesh(mesh)
    bm.free()
    return mesh


def torus_mesh(name, major, minor, segments=64, sides=10):
    vertices, faces = [], []
    for i in range(segments):
        u = 2.0 * math.pi * i / segments
        for j in range(sides):
            v = 2.0 * math.pi * j / sides
            ring = major + minor * math.cos(v)
            vertices.append((ring * math.cos(u), ring * math.sin(u), minor * math.sin(v)))
    for i in range(segments):
        for j in range(sides):
            i1, j1 = (i + 1) % segments, (j + 1) % sides
            faces.append((i * sides + j, i1 * sides + j, i1 * sides + j1, i * sides + j1))
    return mesh_from_pydata(name, vertices, faces, smooth=True)


def annulus_mesh(name, inner, outer, z, segments=64):
    vertices = [(r * math.cos(2 * math.pi * i / segments), r * math.sin(2 * math.pi * i / segments), z)
                for r in (inner, outer) for i in range(segments)]
    faces = [(i, (i + 1) % segments, segments + (i + 1) % segments, segments + i)[::-1] for i in range(segments)]
    return mesh_from_pydata(name, vertices, faces)


def terminal_mesh(name, scale, height):
    bm = bmesh.new()
    bmesh.ops.create_cone(bm, cap_ends=True, cap_tris=False, segments=48,
                          radius1=1.45 * scale, radius2=1.25 * scale, depth=height)
    bmesh.ops.translate(bm, verts=bm.verts[:], vec=(0.0, 0.0, height / 2.0))
    mesh = bpy.data.meshes.new(name)
    bm.to_mesh(mesh)
    bm.free()
    return mesh


def create_obelisk(obelisk, ground_z, collection, metal):
    s = CFG.OBELISK_SCALE
    x, y = (float(v) for v in lonlat_to_xy(obelisk.lon, obelisk.lat))
    glow_color = (*obelisk.color, 1.0)
    glow = principled_material(f"PRIM_Obelisk_Glow_{obelisk.name}", glow_color, 0.3,
                               emission=glow_color, strength=CFG.OBELISK_EMISSION)
    tag = f"PRIM_Obelisk_{obelisk.name}"
    root = new_object(tag, None, collection, location=(x, y, ground_z))
    root.empty_display_type, root.empty_display_size = "PLAIN_AXES", 1.5 * s

    terminal_height = 0.4 * s
    terminal = terminal_mesh(f"{tag}_Terminal", s, terminal_height)
    terminal.materials.append(metal)
    new_object(f"{tag}_Terminal", terminal, collection, parent=root)
    ring = annulus_mesh(f"{tag}_Sello", 0.75 * s, 1.0 * s, terminal_height + 0.004 * s)
    ring.materials.append(glow)
    new_object(f"{tag}_Sello", ring, collection, parent=root)

    spire_base = terminal_height + CFG.OBELISK_HOVER * s
    spire = spire_mesh(f"{tag}_Aguja", s)
    spire.materials.append(metal)
    spire.materials.append(glow)
    new_object(f"{tag}_Aguja", spire, collection, location=(0.0, 0.0, spire_base), parent=root)
    halo = torus_mesh(f"{tag}_Halo", 1.15 * s, 0.05 * s)
    halo.materials.append(glow)
    halo_obj = new_object(f"{tag}_Halo", halo, collection, location=(0.0, 0.0, spire_base + 1.1 * s), parent=root)
    halo_obj.rotation_euler = (math.radians(9.0), math.radians(-6.0), 0.0)

    # Luz de área bajo el obelisco: por defecto emite hacia −Z (el suelo).
    light = bpy.data.lights.new(f"{tag}_Luz", "AREA")
    light.shape, light.size = "DISK", 2.4 * s
    light.energy, light.color = CFG.OBELISK_LIGHT_POWER, obelisk.color
    new_object(f"{tag}_Luz", light, collection, location=(0.0, 0.0, spire_base - 0.25 * s), parent=root)
    return root


