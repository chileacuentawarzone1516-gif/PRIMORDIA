def reset_scene(scene):
    """Vacía la escena (cubo, cámara y luz por defecto incluidos) y purga los
    datos de ejecuciones anteriores para que volver a ejecutar no duplique nada."""
    for obj in list(scene.objects):
        bpy.data.objects.remove(obj, do_unlink=True)
    for collection in [c for c in bpy.data.collections if c.name.startswith("PRIMORDIA")]:
        bpy.data.collections.remove(collection)
    for blocks in (bpy.data.meshes, bpy.data.curves, bpy.data.materials, bpy.data.textures,
                   bpy.data.lights, bpy.data.cameras, bpy.data.node_groups, bpy.data.images):
        for block in list(blocks):
            owned = block.name.startswith(PRIM_PREFIX)
            orphan = block.users == 0 and not block.use_fake_user and blocks is not bpy.data.images
            if owned or orphan:
                blocks.remove(block)


