"""
PRIMORDIA · The Island — maqueta 3D procedural para Blender
===========================================================

Genera desde cero una recreación de "The Island" (ARK: Survival Evolved /
Ascended) con aspecto de maqueta digital premium y la exporta a .glb.

Uso
---
* Blender 4.0 o superior (validado en 4.2 LTS, 4.5 LTS y 5.0): pestaña
  Scripting → Abrir este archivo → Run Script. Sin add-ons ni archivos externos.
  El progreso se ve en la consola del sistema (Window → Toggle System Console).
* Sin interfaz (CI / automatización):
      blender -b -P primordia_island.py -- --glb isla.glb --render vista.png
  Opciones: --glb RUTA · --no-export · --render PNG · --render-map PNG ·
            --engine EEVEE|CYCLES · --samples N · --grid N · --style REALISTIC|LOW_POLY

Qué construye
-------------
1. Terreno: cuadrícula lat/lon 0‒100 (1 unidad = 1 grado ARK) de 512×512
   subdivisiones. Costa, ríos y lagos salen de anillos vectoriales extraídos del
   mapa in-game (bloque GEO-DATA); volcán, macizos del norte y este y colinas se
   modelan con perfiles analíticos + ruido; el detalle final lo aportan
   modificadores Displace con texturas procedurales Musgrave y Clouds.
2. Material PBR por nodos que pinta por altura (Z), pendiente y bioma.
3. Obeliscos rojo, verde y azul en sus coordenadas in-game, emisivos y con luz
   de área de su color apuntando al suelo.
4. Sol, cielo físico, cámara aérea inclinada y cámara cenital de mapa.
5. Horneado del material a texturas PBR y exportación .glb con normales suaves
   unificadas, para que los degradados sobrevivan en cualquier visor glTF.
"""

