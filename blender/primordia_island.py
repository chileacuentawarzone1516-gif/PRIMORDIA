def mesh_from_quads(name, vertices, quads):
    """Malla grande desde numpy con foreach_set (órdenes de magnitud más rápido que from_pydata)."""
    mesh = bpy.data.meshes.new(name)
    mesh.vertices.add(len(vertices))
    mesh.vertices.foreach_set("co", vertices.astype(np.float32).ravel())
    mesh.loops.add(quads.size)
    mesh.loops.foreach_set("vertex_index", quads.astype(np.int32).ravel())
    mesh.polygons.add(len(quads))
    mesh.polygons.foreach_set("loop_start", np.arange(0, quads.size, 4, dtype=np.int32))
    mesh.update(calc_edges=True)
    mesh.validate(clean_customdata=False)
    return mesh


def mesh_from_pydata(name, vertices, faces, smooth=False):
    mesh = bpy.data.meshes.new(name)
    mesh.from_pydata(vertices, [], faces)
    unify_normals(mesh, smooth=smooth, upward=False)
    return mesh


def unify_normals(mesh, smooth, upward=True):
    """Orientación coherente de caras (y hacia +Z en el terreno) + sombreado
    uniforme: el exportador glTF escribe normales por vértice continuas y los
    degradados de color no se rompen en costuras."""
    bm = bmesh.new()
    bm.from_mesh(mesh)
    bmesh.ops.recalc_face_normals(bm, faces=bm.faces[:])
    if upward:
        bm.normal_update()
        if sum(face.normal.z for face in bm.faces) < 0.0:
            bmesh.ops.reverse_faces(bm, faces=bm.faces[:])
    bm.to_mesh(mesh)
    bm.free()
    mesh.polygons.foreach_set("use_smooth", np.full(len(mesh.polygons), smooth, dtype=bool))
    mesh.update()


def set_vertex_group(obj, name, weights, levels=32):
    group = obj.vertex_groups.new(name=name)
    quantized = np.round(np.clip(weights, 0.0, 1.0) * levels).astype(np.int32)
    for level in np.unique(quantized):
        if level > 0:
            group.add(np.flatnonzero(quantized == level).tolist(), level / levels, "REPLACE")


def add_point_attribute(mesh, name, values):
    attribute = mesh.attributes.new(name, "FLOAT", "POINT")
    attribute.data.foreach_set("value", values.astype(np.float32))


def add_planar_uv(mesh, name="UVMap"):
    """UV = proyección cenital del mapa: la textura horneada es el propio mapa."""
    uv_layer = mesh.uv_layers.new(name=name)
    coords = np.empty(len(mesh.vertices) * 3, dtype=np.float32)
    mesh.vertices.foreach_get("co", coords)
    loop_vertex = np.empty(len(mesh.loops), dtype=np.int32)
    mesh.loops.foreach_get("vertex_index", loop_vertex)
    uv = (coords.reshape(-1, 3)[loop_vertex, :2] + 50.0) / 100.0
    uv_layer.data.foreach_set("uv", uv.astype(np.float32).ravel())


def new_texture(name, kind, **props):
    texture = bpy.data.textures.new(name, kind)
    for key, value in props.items():
        setattr(texture, key, value)
    return texture


def calibrated_displace(obj, name, texture, vertex_group, amplitude, samples=4096):
    """Displace cuyo mid-level es la media real de la textura: añade detail ±amplitude
    sin elevar ni hundir el conjunto (Musgrave no está centrado en 0.5)."""
    points = np.random.default_rng(CFG.SEED).uniform((-50.0, -50.0, 0.0), (50.0, 50.0, 8.0), (samples, 3))
    values = np.array([texture.evaluate(tuple(point))[3] for point in points])
    modifier = obj.modifiers.new(name, "DISPLACE")
    modifier.texture = texture
    modifier.texture_coords = "LOCAL"
    modifier.direction = "Z"
    modifier.vertex_group = vertex_group
    modifier.mid_level = float(values.mean())
    modifier.strength = amplitude / max(float(values.std()), 1e-6)
    return modifier


def create_terrain(field, collection):
    n = len(field.xs)
    grid_x, grid_y = np.meshgrid(field.xs, field.ys)
    vertices = np.column_stack([grid_x.ravel(), grid_y.ravel(), field.heights.ravel()])
    index = np.arange(n * n, dtype=np.int32).reshape(n, n)
    quads = np.stack([index[:-1, :-1], index[:-1, 1:], index[1:, 1:], index[1:, :-1]], axis=-1).reshape(-1, 4)

    mesh = mesh_from_quads("PRIM_Terrain", vertices, quads)
    for name, values in field.masks.items():
        add_point_attribute(mesh, name, values.ravel())
    add_planar_uv(mesh)
    unify_normals(mesh, smooth=CFG.STYLE != "LOW_POLY")
    terrain = new_object("PRIM_Terrain", mesh, collection)
    for name, weights in field.weights.items():
        set_vertex_group(terrain, name, weights.ravel())

    # Detalle procedural no destructivo (se aplica al exportar/hornear).
    musgrave = new_texture("PRIM_Tex_Musgrave", "MUSGRAVE", musgrave_type="RIDGED_MULTIFRACTAL",
                           noise_basis="IMPROVED_PERLIN", noise_scale=2.4, octaves=6.0,
                           lacunarity=2.1, dimension_max=0.9, offset=1.0, gain=2.0)
    clouds = new_texture("PRIM_Tex_Clouds", "CLOUDS", noise_basis="IMPROVED_PERLIN",
                         noise_type="SOFT_NOISE", noise_scale=1.8, noise_depth=4)
    calibrated_displace(terrain, "PRIM_Displace_Musgrave", musgrave, VG_RELIEF, amplitude=0.4)
    calibrated_displace(terrain, "PRIM_Displace_Clouds", clouds, VG_LAND, amplitude=0.035)
    if CFG.STYLE == "LOW_POLY":
        decimate = terrain.modifiers.new("PRIM_Decimate_LowPoly", "DECIMATE")
        decimate.decimate_type = "COLLAPSE"
        decimate.ratio = CFG.LOW_POLY_RATIO
        decimate.use_collapse_triangulate = True
    return terrain


def box_faces(offset=0, top=True, bottom=True):
    faces = [(0, 4, 5, 1), (1, 5, 6, 2), (2, 6, 7, 3), (3, 7, 4, 0)]
    if top:
        faces.append((0, 1, 2, 3))
    if bottom:
        faces.append((7, 6, 5, 4))
    return [tuple(offset + i for i in face) for face in faces]


def box_vertices(half_x, half_y, z_top, z_bottom):
    corners = ((-half_x, -half_y), (half_x, -half_y), (half_x, half_y), (-half_x, half_y))
    return [(x, y, z_top) for x, y in corners] + [(x, y, z_bottom) for x, y in corners]


