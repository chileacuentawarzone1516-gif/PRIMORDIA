def apply_cli_overrides():
    """Permite `blender -b -P primordia_island.py -- --glb x.glb --render y.png`."""
    argv = sys.argv[sys.argv.index("--") + 1:] if "--" in sys.argv else []
    parser = argparse.ArgumentParser(prog="primordia_island.py", description="PRIMORDIA · The Island")
    parser.add_argument("--glb", help="ruta del .glb exportado")
    parser.add_argument("--no-export", action="store_true", help="no hornear ni exportar .glb")
    parser.add_argument("--render", help="guardar render PNG de la cámara aérea")
    parser.add_argument("--render-map", help="guardar render PNG de la cámara cenital")
    parser.add_argument("--engine", choices=("EEVEE", "CYCLES"))
    parser.add_argument("--samples", type=int, help="muestras de render")
    parser.add_argument("--grid", type=int, help="subdivisiones por lado (≥ 200)")
    parser.add_argument("--style", choices=("REALISTIC", "LOW_POLY"))
    args, ignored = parser.parse_known_args(argv)
    if ignored:
        log(f"Argumentos ignorados (no reconocidos): {' '.join(ignored)}")
    if args.glb:
        CFG.GLB_PATH = args.glb
    if args.no_export:
        CFG.EXPORT_GLB = False
    if args.engine:
        CFG.RENDER_ENGINE = args.engine
    if args.grid:
        CFG.GRID_SUBDIVISIONS = args.grid
    if args.style:
        CFG.STYLE = args.style
    return args


def validate_config():
    if bpy.app.version < (4, 0, 0):
        raise RuntimeError("PRIMORDIA requiere Blender 4.0 o superior (validado en 4.2 LTS, 4.5 LTS y 5.0).")
    if CFG.GRID_SUBDIVISIONS < 200:
        raise ValueError("GRID_SUBDIVISIONS debe ser ≥ 200 para conservar ríos y costa.")
    if CFG.STYLE not in ("REALISTIC", "LOW_POLY"):
        raise ValueError("STYLE debe ser 'REALISTIC' o 'LOW_POLY'.")


def render_still(scene, camera, path, samples=None):
    previous_camera = scene.camera
    scene.camera = camera
    if samples:
        scene.eevee.taa_render_samples = samples
        scene.cycles.samples = samples
    scene.render.image_settings.file_format = "PNG"
    scene.render.filepath = bpy.path.abspath(path)
    bpy.ops.render.render(write_still=True)
    scene.camera = previous_camera
    log(f"Render guardado: {scene.render.filepath}")


def main():
    started = time.perf_counter()
    args = apply_cli_overrides()
    validate_config()
    scene = bpy.context.scene
    ensure_object_mode()
    reset_scene(scene)
    collections = create_collections(scene)

    log(f"Modelando relieve ({CFG.GRID_SUBDIVISIONS}×{CFG.GRID_SUBDIVISIONS})…")
    field = build_heightfield()
    log("Construyendo malla, materiales y maqueta…")
    terrain = create_terrain(field, collections["terrain"])
    terrain_material = build_terrain_material()
    terrain.data.materials.append(terrain_material.material)

    ocean = create_ocean(collections["terrain"], build_water_material())
    pedestal = create_pedestal(collections["terrain"],
                               principled_material("PRIM_Pedestal", color("pedestal"), 0.45))
    exported = [terrain, ocean, pedestal]
    if CFG.SHOW_NAMEPLATE:
        brass = principled_material("PRIM_Brass", color("brass"), 0.32, metallic=0.55)
        exported.append(create_nameplate(collections["terrain"], brass))

    metal = principled_material("PRIM_Obelisk_Metal", color("obelisk_metal"), 0.28, metallic=0.95)
    for obelisk in OBELISKS:
        x, y = (float(v) for v in lonlat_to_xy(obelisk.lon, obelisk.lat))
        root = create_obelisk(obelisk, sample_grid(field.heights, field.xs, field.ys, x, y),
                              collections["obelisks"], metal)
        exported.extend([root, *root.children])

    create_sun(collections["rig"])
    setup_world(scene)
    aerial = create_camera("PRIM_Cam_Aerial", collections["rig"], (0.0, -124.0, 98.0),
                           target=(0.0, -9.0, -4.0), lens=40.0)
    map_camera = create_camera("PRIM_Cam_Map", collections["rig"], (0.0, 0.0, 160.0), ortho_scale=104.0)
    scene.camera = aerial
    configure_render(scene, CFG.RENDER_ENGINE)
    add_glow_compositing(scene)
    log(f"Escena lista en {time.perf_counter() - started:.1f} s · "
        f"{len(terrain.data.vertices):,} vértices · altura máx. {field.heights.max():.1f}")

    if CFG.EXPORT_GLB:
        log(f"Horneando texturas PBR {CFG.BAKE_RESOLUTION}px y exportando .glb…")
        albedo, orm = bake_terrain_textures(scene, terrain, terrain_material)
        export_glb(terrain, build_glb_terrain_material(albedo, orm),
                   [obj for obj in exported if obj.type in {"MESH", "EMPTY"}])
    if args.render:
        render_still(scene, aerial, args.render, args.samples)
    if args.render_map:
        render_still(scene, map_camera, args.render_map, args.samples)
    configure_viewports()
    log(f"PRIMORDIA generado en {time.perf_counter() - started:.1f} s")


if __name__ == "__main__":
    main()
