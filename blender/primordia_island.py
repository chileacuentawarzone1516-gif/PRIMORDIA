def _socket(sockets, identifier):
    return next(s for s in sockets if s.identifier == identifier)


class NodeBuilder:
    """Mini-DSL para árboles de nodos legibles, con maquetación automática."""

    def __init__(self, owner):
        if owner.node_tree is None:
            owner.use_nodes = True
        self.tree = owner.node_tree
        self.tree.nodes.clear()
        self.nodes, self.links = self.tree.nodes, self.tree.links

    def new(self, bl_idname, label=None, **props):
        node = self.nodes.new(bl_idname)
        if label:
            node.name = node.label = label
        for key, value in props.items():
            setattr(node, key, value)
        return node

    def feed(self, socket, value):
        if isinstance(value, bpy.types.NodeSocket):
            self.links.new(value, socket)
        elif value is not None:
            socket.default_value = value

    def set_inputs(self, node, values):
        for name, value in values.items():
            self.feed(node.inputs[name], value)
        return node

    def math(self, operation, a, b=0.0):
        node = self.new("ShaderNodeMath", operation=operation)
        self.feed(node.inputs[0], a)
        self.feed(node.inputs[1], b)
        return node.outputs[0]

    def remap(self, value, from_min, from_max, to_min=0.0, to_max=1.0, smooth=True):
        node = self.new("ShaderNodeMapRange", interpolation_type="SMOOTHSTEP" if smooth else "LINEAR", clamp=True)
        return self.set_inputs(node, {"Value": value, "From Min": from_min, "From Max": from_max,
                                      "To Min": to_min, "To Max": to_max}).outputs["Result"]

    def mix(self, factor, a, b, data_type="RGBA"):
        kind = "Color" if data_type == "RGBA" else "Float"
        node = self.new("ShaderNodeMix", data_type=data_type, clamp_factor=True)
        self.feed(_socket(node.inputs, "Factor_Float"), factor)
        self.feed(_socket(node.inputs, f"A_{kind}"), a)
        self.feed(_socket(node.inputs, f"B_{kind}"), b)
        return _socket(node.outputs, f"Result_{kind}")

    def ramp(self, factor, stops):
        node = self.new("ShaderNodeValToRGB")
        elements = node.color_ramp.elements
        (first_pos, first_col), (last_pos, last_col) = stops[0], stops[-1]
        elements[0].position, elements[0].color = first_pos, color(first_col)
        elements[-1].position, elements[-1].color = last_pos, color(last_col)
        for position, name in stops[1:-1]:
            elements.new(position).color = color(name)
        self.feed(node.inputs["Fac"], factor)
        return node.outputs["Color"]

    def noise(self, vector, scale, detail=4.0, roughness=0.55):
        node = self.new("ShaderNodeTexNoise")
        return self.set_inputs(node, {"Vector": vector, "Scale": scale, "Detail": detail,
                                      "Roughness": roughness}).outputs["Fac"]

    def attribute(self, name):
        node = self.new("ShaderNodeAttribute", attribute_type="GEOMETRY", attribute_name=name)
        return node.outputs["Fac"]

    def arrange(self, spacing=(300, 190)):
        depth = {node.name: 0 for node in self.nodes}
        changed = True
        while changed:
            changed = False
            for link in self.links:
                wanted = depth[link.to_node.name] + 1
                if depth[link.from_node.name] < wanted:
                    depth[link.from_node.name], changed = wanted, True
        columns = {}
        for node in self.nodes:
            columns.setdefault(depth[node.name], []).append(node)
        for column, nodes in columns.items():
            for row, node in enumerate(nodes):
                node.location = (-column * spacing[0], (len(nodes) / 2.0 - row) * spacing[1])


def make_transparent(material):
    if hasattr(material, "surface_render_method"):      # EEVEE Next (4.2+)
        material.surface_render_method = "BLENDED"
    if hasattr(material, "blend_method"):
        material.blend_method = "BLEND"
    material.use_backface_culling = False


def principled_material(name, base, roughness, metallic=0.0, emission=None, strength=0.0):
    material = bpy.data.materials.new(name)
    b = NodeBuilder(material)
    bsdf = b.set_inputs(b.new("ShaderNodeBsdfPrincipled"), {
        "Base Color": base, "Roughness": roughness, "Metallic": metallic})
    if emission is not None:
        b.set_inputs(bsdf, {"Emission Color": emission, "Emission Strength": strength})
    b.feed(b.new("ShaderNodeOutputMaterial").inputs["Surface"], bsdf.outputs["BSDF"])
    b.arrange()
    material.diffuse_color = base
    return material


TerrainMaterial = namedtuple("TerrainMaterial", "material output channels")


def build_terrain_material():
    """Material PBR procedural: biomas por altura (Z), pendiente y regiones.

    Capas (de abajo arriba): selva → secuoyas → pantano → arena → roca →
    obsidiana → nieve → fondo marino. Cada capa mezcla color, rugosidad y
    metalicidad con el mismo peso, así el horneado PBR es coherente.
    """
    material = bpy.data.materials.new("PRIM_Terrain")
    b = NodeBuilder(material)

    coords = b.new("ShaderNodeTexCoord").outputs["Object"]
    position = b.new("ShaderNodeSeparateXYZ")
    b.feed(position.inputs[0], coords)
    normal = b.new("ShaderNodeSeparateXYZ")
    b.feed(normal.inputs[0], b.new("ShaderNodeNewGeometry").outputs["Normal"])
    z, y = position.outputs["Z"], position.outputs["Y"]
    slope = b.math("SUBTRACT", 1.0, normal.outputs["Z"])          # 0 llano · 1 vertical

    snow_region, redwood_region = b.attribute(ATTR_SNOW), b.attribute(ATTR_REDWOOD)
    swamp_region, volcanic, beach = b.attribute(ATTR_SWAMP), b.attribute(ATTR_VOLCANIC), b.attribute(ATTR_BEACH)
    n_large = b.noise(coords, 0.045, 3.0, 0.5)                      # manchas de ~20 u
    n_mid = b.noise(coords, 0.22, 5.0, 0.6)                         # variación de bioma
    n_fine = b.noise(coords, 1.8, 6.0, 0.6)                         # grano de textura
    jitter = b.math("SUBTRACT", n_mid, 0.5)

    # Colores por bioma.
    jungle = b.ramp(n_mid, [(0.35, "grass_dark"), (0.55, "grass"), (0.74, "grass_light")])
    jungle = b.mix(b.math("MULTIPLY", b.remap(n_large, 0.6, 0.75), 0.35), jungle, color("earth"))
    redwood = b.ramp(n_fine, [(0.3, "redwood_floor"), (0.46, "redwood_bark"), (0.6, "redwood_canopy")])
    swamp = b.ramp(n_large, [(0.4, "swamp"), (0.65, "swamp_murk")])
    sand = b.ramp(n_fine, [(0.3, "sand_dark"), (0.7, "sand")])
    rock = b.ramp(n_fine, [(0.35, "rock_dark"), (0.65, "rock_light")])
    frozen_lowland = b.math("MULTIPLY", snow_region, b.remap(z, 0.8, 2.4, 1.0, 0.0))
    ice = b.math("MULTIPLY", frozen_lowland, b.remap(n_large, 0.45, 0.6))
    snow = b.mix(ice, color("snow"), color("ice"))
    seabed = b.ramp(b.remap(z, CFG.EDGE_DEPTH, 0.0, smooth=False),
                    [(0.0, "seabed_deep"), (0.55, "seabed"), (0.85, "seabed_shallow"), (1.0, "seabed_sand")])

    # Pesos de cada capa.
    w_swamp = b.math("MULTIPLY", swamp_region, b.remap(z, 0.2, 0.5, 1.0, 0.0))
    shoreline = b.remap(b.math("ADD", z, b.math("MULTIPLY", jitter, 0.2)), 0.2, 0.38, 1.0, 0.0)
    w_sand = b.math("MULTIPLY", b.math("MULTIPLY", beach, shoreline), b.remap(slope, 0.3, 0.45, 1.0, 0.0))
    rock_score = b.math("ADD", b.math("MULTIPLY", slope, 1.6),
                        b.math("ADD", b.math("MULTIPLY", b.remap(z, 3.0, 6.5), 0.5), b.math("MULTIPLY", jitter, 0.35)))
    w_rock = b.math("MAXIMUM", b.remap(rock_score, 0.55, 0.8), b.math("MULTIPLY", volcanic, 0.9))
    crater = b.remap(b.math("ADD", volcanic, b.math("MULTIPLY", jitter, 0.5)), 0.86, 0.97)
    w_obsidian = b.math("MAXIMUM", b.math("MULTIPLY", volcanic, crater),
                        b.math("MULTIPLY", w_rock, b.math("MULTIPLY", b.remap(z, 8.0, 10.0), 0.5)))
    snowline = b.remap(y, -10.0, 45.0, 9.2, 5.2, smooth=False)       # la nieve baja hacia el norte
    altitude_snow = b.remap(b.math("ADD", b.math("SUBTRACT", z, snowline), b.math("MULTIPLY", jitter, 1.2)), 0.0, 0.6)
    region_snow = b.math("MULTIPLY", snow_region, b.remap(z, 0.1, 0.35))
    w_snow = b.math("MULTIPLY", b.math("MAXIMUM", region_snow, altitude_snow),
                    b.math("MULTIPLY", b.remap(slope, 0.5, 0.72, 1.0, 0.0), b.math("SUBTRACT", 1.0, volcanic)))
    w_seabed = b.remap(z, -0.25, 0.02, 1.0, 0.0)

    base_color, roughness, metallic = jungle, 0.42, 0.0               # selva: baja rugosidad
    for weight, layer_color, layer_rough, layer_metal in (
        (redwood_region, redwood, 0.6, 0.0),
        (w_swamp, swamp, 0.12, 0.0),
        (w_sand, sand, 0.92, 0.0),                                    # arena mate
        (w_rock, rock, 0.72, 0.0),
        (w_obsidian, color("obsidian"), 0.2, 0.75),                   # obsidiana metálica
        (w_snow, snow, 0.5, 0.0),                                     # nieve: rugosidad alta
        (w_seabed, seabed, 0.55, 0.0),
    ):
        base_color = b.mix(weight, base_color, layer_color)
        roughness = b.mix(weight, roughness, layer_rough, "FLOAT")
        metallic = b.mix(weight, metallic, layer_metal, "FLOAT")

    micro = b.noise(coords, 6.0, 4.0, 0.6)
    bump = b.set_inputs(b.new("ShaderNodeBump"), {"Strength": 0.08, "Distance": 0.03, "Height": micro})
    bsdf = b.set_inputs(b.new("ShaderNodeBsdfPrincipled"), {
        "Base Color": base_color, "Roughness": roughness, "Metallic": metallic, "Normal": bump.outputs["Normal"]})
    output = b.new("ShaderNodeOutputMaterial")
    b.feed(output.inputs["Surface"], bsdf.outputs["BSDF"])
    b.arrange()
    material.diffuse_color = color("grass")
    return TerrainMaterial(material, output, {"base_color": base_color, "roughness": roughness, "metallic": metallic})


