VG_RELIEF, VG_LAND = "PRIM_Relieve", "PRIM_Tierra"


def peak_field(peak, grid_x, grid_y, noise):
    cx, cy = lonlat_to_xy(peak.lon, peak.lat)
    dx, dy = grid_x - cx, grid_y - cy
    r = np.hypot(dx, dy)
    if peak.kind == "volcano":
        # Estratovolcán: flancos cóncavos con cárcavas radiales y cráter en cuenco.
        gullies = 1.0 + 0.10 * np.sin(22.0 * np.arctan2(dy, dx) + 3.0 * noise(grid_x / 2.5, grid_y / 2.5))
        radius = peak.radius * gullies
        cone = peak.height * np.clip(1.0 - r / radius, 0.0, 1.0) ** 1.5
        crater_r = 0.14 * peak.radius
        rim = peak.height * (1.0 - crater_r / radius) ** 1.5
        bowl = rim - 0.2 * peak.height * (1.0 - (r / crater_r) ** 2)
        return np.where(r < crater_r, bowl, cone)
    shape = np.exp(-2.6 * (r / peak.radius) ** 2)
    if peak.kind == "mountain":
        crests = noise.ridged(grid_x / 2.2 + cx, grid_y / 2.2 + cy, octaves=5)
        return peak.height * shape * (0.7 + 0.5 * crests)
    return peak.height * shape * (0.85 + 0.3 * noise.fbm(grid_x / 3.0 + cx, grid_y / 3.0 + cy, octaves=3))


def ridge_field(ridge, grid_x, grid_y, noise):
    points = [tuple(float(v) for v in lonlat_to_xy(lon, lat)) for lon, lat in ridge.points]
    distance = distance_to_polyline(grid_x, grid_y, points)
    crests = noise.ridged(grid_x / 2.0, grid_y / 2.0, octaves=5)
    return ridge.height * np.exp(-2.2 * (distance / ridge.width) ** 2) * (0.65 + 0.5 * crests)


def build_heightfield():
    n = CFG.GRID_SUBDIVISIONS + 1
    xs = ys = np.linspace(-50.0, 50.0, n)
    cell = xs[1] - xs[0]
    grid_x, grid_y = np.meshgrid(xs, ys)
    noise = Perlin2D(CFG.SEED)

    coast = parse_rings(COAST_RINGS)
    dist = signed_distance(coast, rasterize_even_odd(coast, xs, ys), xs, ys)
    land_fade = smoothstep(0.0, 2.5, dist)

    def region(rings):
        return rasterize_even_odd(parse_rings(rings), xs, ys).astype(np.float64)

    snow_raw = region(SNOW_REGION_RINGS)
    snow = gaussian_blur(snow_raw, 1.2, cell)
    redwood = gaussian_blur(region(REDWOOD_REGION_RINGS), 1.5, cell)
    swamp = gaussian_blur(region(SWAMP_REGION_RINGS), 1.0, cell) * smoothstep(-0.5, 0.5, dist)
    # Playas solo frente a aguas abiertas: los ríos estrechos (< ~1.8 u) no cuentan.
    beach = smoothstep(0.06, 0.25, gaussian_blur((dist < -0.9).astype(np.float64), 1.0, cell))

    # 1) Perfil costero continuo: playas anchas y bajas frente al mar, orillas
    #    más abruptas en los ríos; plataforma, talud y relieve submarino en el agua.
    seabed_relief = 0.35 * noise.fbm(grid_x / 5.0, grid_y / 5.0, octaves=4) * smoothstep(0.0, 4.0, -dist)
    land_edge = dist.clip(min=0.0)
    beach_profile = 0.36 * (1.0 - np.exp(-land_edge / 1.6))
    bank_profile = 0.8 * (1.0 - np.exp(-land_edge / 0.7))
    shore = np.where(
        dist >= 0.0,
        bank_profile + beach * (beach_profile - bank_profile),
        -1.25 * (1.0 - np.exp(dist / 1.6)) - 1.7 * smoothstep(0.0, 12.0, -dist) + seabed_relief,
    )
    # 2) Llanuras onduladas que ganan altura lejos del mar.
    interior = smoothstep(1.0, 8.0, dist) * (1.25 + 0.9 * noise.fbm(grid_x / 13.0, grid_y / 13.0, octaves=5))
    # 3) Tierras altas nevadas del norte: mesetas con crestas.
    highlands = gaussian_blur(snow_raw, 3.0, cell) * (2.0 + 1.6 * noise.ridged(grid_x / 5.0, grid_y / 5.0))
    # 4) Volcán, montañas, colinas y cordilleras.
    relief = sum(peak_field(peak, grid_x, grid_y, noise) for peak in RELIEF_PEAKS)
    for ridge in RELIEF_RIDGES:
        relief = relief + ridge_field(ridge, grid_x, grid_y, noise)
    heights = (shore + land_fade * (interior + highlands + relief)) * CFG.HEIGHT_SCALE

    # 5) Pantano: lámina húmeda casi a ras del agua.
    swamp_level = 0.07 + 0.04 * noise.fbm(grid_x / 1.5, grid_y / 1.5, octaves=3)
    heights += swamp * (swamp_level - heights)
    # 6) Borde de la maqueta nivelado para encajar con el pedestal.
    border = smoothstep(47.0, 49.5, np.maximum(np.abs(grid_x), np.abs(grid_y)))
    heights += border * (CFG.EDGE_DEPTH - heights)
    # 7) Plataformas niveladas para las terminales de los obeliscos.
    pads = np.zeros_like(heights)
    for obelisk in OBELISKS:
        ox, oy = lonlat_to_xy(obelisk.lon, obelisk.lat)
        r = np.hypot(grid_x - ox, grid_y - oy) / CFG.OBELISK_SCALE
        level = max(float(heights[r < 1.4].mean()), 0.3)
        pad = smoothstep(2.6, 1.5, r)
        heights += pad * (level - heights)
        pads = np.maximum(pads, pad)

    volcanic = np.zeros_like(heights)
    for peak in (p for p in RELIEF_PEAKS if p.kind == "volcano"):
        px, py = lonlat_to_xy(peak.lon, peak.lat)
        r = np.hypot(grid_x - px, grid_y - py)
        volcanic = np.maximum(volcanic, smoothstep(peak.radius * 0.95, peak.radius * 0.25, r))

    return Heightfield(
        xs=xs, ys=ys, heights=heights,
        masks={ATTR_SNOW: snow, ATTR_REDWOOD: redwood, ATTR_SWAMP: swamp,
               ATTR_VOLCANIC: volcanic, ATTR_BEACH: beach},
        weights={
            VG_RELIEF: smoothstep(1.5, 6.0, heights) * land_fade * (1.0 - pads),
            VG_LAND: smoothstep(0.3, 2.5, dist) * (1.0 - swamp) * (1.0 - pads),
        },
    )


