def select_only(objects, active):
    for obj in bpy.context.view_layer.objects:
        obj.select_set(obj in objects)
    bpy.context.view_layer.objects.active = active


def bake_channel(terrain_material, channel, image_name, size, non_color):
    """Hornea un canal del material procedural vía emisión (sin influencia de luces)."""
    nodes, links = terrain_material.material.node_tree.nodes, terrain_material.material.node_tree.links
    image = bpy.data.images.new(image_name, size, size, alpha=False, float_buffer=non_color)
    image.colorspace_settings.name = "Non-Color" if non_color else "sRGB"
    target = nodes.new("ShaderNodeTexImage")
    target.image = image
    emission = nodes.new("ShaderNodeEmission")
    links.new(terrain_material.channels[channel], emission.inputs["Color"])
    surface = terrain_material.output.inputs["Surface"]
    original = surface.links[0].from_socket
    links.new(emission.outputs["Emission"], surface)
    nodes.active = target
    try:
        bpy.ops.object.bake(type="EMIT", margin=4, use_clear=True)
    finally:
        links.new(original, surface)
        nodes.remove(emission)
        nodes.remove(target)
    return image


def bake_terrain_textures(scene, terrain, terrain_material):
    size = CFG.BAKE_RESOLUTION
    previous_engine, previous_samples = scene.render.engine, scene.cycles.samples
    set_render_engine(scene, "CYCLES")
    scene.cycles.samples = CFG.BAKE_SAMPLES
    cycles_addon = bpy.context.preferences.addons.get("cycles")
    if cycles_addon and cycles_addon.preferences.has_active_device():
        scene.cycles.device = "GPU"             # usa la GPU configurada en Preferencias
    select_only([terrain], terrain)
    try:
        albedo = bake_channel(terrain_material, "base_color", "PRIM_Terrain_BaseColor", size, non_color=False)
        rough = bake_channel(terrain_material, "roughness", "PRIM_Bake_Roughness", size, non_color=True)
        metal = bake_channel(terrain_material, "metallic", "PRIM_Bake_Metallic", size, non_color=True)
    finally:
        scene.render.engine, scene.cycles.samples = previous_engine, previous_samples

    pixels = size * size * 4
    rough_px, metal_px = np.empty(pixels, np.float32), np.empty(pixels, np.float32)
    rough.pixels.foreach_get(rough_px)
    metal.pixels.foreach_get(metal_px)
    orm_px = np.ones((size * size, 4), np.float32)
    orm_px[:, 1], orm_px[:, 2] = rough_px[0::4], metal_px[0::4]
    orm = bpy.data.images.new("PRIM_Terrain_ORM", size, size, alpha=False)
    orm.colorspace_settings.name = "Non-Color"
    orm.pixels.foreach_set(orm_px.ravel())
    bpy.data.images.remove(rough)
    bpy.data.images.remove(metal)
    for image in (albedo, orm):
        image.pack()
    return albedo, orm


def resolve_glb_path():
    if CFG.GLB_PATH:
        path = bpy.path.abspath(CFG.GLB_PATH)
    else:
        folder = os.path.dirname(bpy.data.filepath) if bpy.data.filepath else os.path.expanduser("~")
        path = os.path.join(folder, "PRIMORDIA_TheIsland.glb")
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    return os.path.abspath(path)


def gltf_export_options(path):
    wanted = {
        "filepath": path, "export_format": "GLB", "use_selection": True, "export_apply": True,
        "export_yup": True, "export_texcoords": True, "export_normals": True,
        "export_materials": "EXPORT", "export_image_format": "JPEG", "export_jpeg_quality": 90,
        "export_image_quality": 90, "export_cameras": False, "export_lights": False,
        "export_vertex_color": "NONE", "export_colors": False, "export_attributes": False,
        "export_extras": False, "export_draco_mesh_compression_enable": CFG.EXPORT_DRACO,
        "export_draco_mesh_compression_level": 6,
    }
    available = {prop.identifier for prop in bpy.ops.export_scene.gltf.get_rna_type().properties}
    return {key: value for key, value in wanted.items() if key in available}


def export_glb(terrain, glb_material, objects):
    """Exporta con el material horneado; restaura el procedural al terminar."""
    path = resolve_glb_path()
    slot = terrain.material_slots[0]
    procedural = slot.material
    decimate = None
    if CFG.STYLE != "LOW_POLY" and CFG.EXPORT_DECIMATE_RATIO < 1.0:
        decimate = terrain.modifiers.new("PRIM_Decimate_Export", "DECIMATE")
        decimate.decimate_type, decimate.ratio = "COLLAPSE", CFG.EXPORT_DECIMATE_RATIO
    slot.material = glb_material
    select_only(objects, terrain)
    try:
        bpy.ops.export_scene.gltf(**gltf_export_options(path))
    finally:
        slot.material = procedural
        if decimate is not None:
            terrain.modifiers.remove(decimate)
        select_only([], None)
    log(f"GLB exportado: {path} ({os.path.getsize(path) / 1_048_576:.1f} MB)")
    return path


