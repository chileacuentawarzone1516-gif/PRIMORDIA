def smoothstep(edge0, edge1, x):
    t = np.clip((x - edge0) / (edge1 - edge0), 0.0, 1.0)
    return t * t * (3.0 - 2.0 * t)


def lonlat_to_xy(lon, lat):
    """Grados ARK → coordenadas Blender (X = este, Y = norte, origen en el centro)."""
    return np.asarray(lon, dtype=np.float64) - 50.0, 50.0 - np.asarray(lat, dtype=np.float64)


def srgb_to_linear(hex_color, alpha=1.0):
    value = hex_color.lstrip("#")
    channels = (int(value[i:i + 2], 16) / 255.0 for i in (0, 2, 4))
    return (*(c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4 for c in channels), alpha)


def color(name):
    return srgb_to_linear(PALETTE[name])


def parse_rings(rings):
    """Anillos 'lon,lat …' → lista de arrays (k, 2) en coordenadas Blender."""
    parsed = []
    for chunks in rings:
        values = np.array("".join(chunks).replace(",", " ").split(), dtype=np.float64).reshape(-1, 2)
        x, y = lonlat_to_xy(values[:, 0], values[:, 1])
        parsed.append(np.column_stack([x, y]))
    return parsed


def ring_segments(rings):
    starts = np.concatenate(rings)
    ends = np.concatenate([np.roll(ring, -1, axis=0) for ring in rings])
    return starts, ends


def rasterize_even_odd(rings, xs, ys):
    """Relleno par-impar por barrido de filas: islas, lagos y ríos en una pasada."""
    start, end = ring_segments(rings)
    inside = np.zeros((len(ys), len(xs)), dtype=bool)
    for row, y in enumerate(ys):
        crossing = (start[:, 1] > y) != (end[:, 1] > y)
        if not crossing.any():
            continue
        a, b = start[crossing], end[crossing]
        x_cross = np.sort(a[:, 0] + (y - a[:, 1]) * (b[:, 0] - a[:, 0]) / (b[:, 1] - a[:, 1]))
        inside[row] = np.searchsorted(x_cross, xs) % 2 == 1
    return inside


def _nearest_points_on_segments(px, py, start, end, chunk=1024):
    direction = end - start
    length2 = np.maximum((direction ** 2).sum(axis=1), 1e-12)
    qx, qy = np.empty_like(px), np.empty_like(py)
    for s in range(0, len(px), chunk):
        cx, cy = px[s:s + chunk, None], py[s:s + chunk, None]
        t = ((cx - start[:, 0]) * direction[:, 0] + (cy - start[:, 1]) * direction[:, 1]) / length2
        t = np.clip(t, 0.0, 1.0)
        nx, ny = start[:, 0] + t * direction[:, 0], start[:, 1] + t * direction[:, 1]
        best = np.argmin((nx - cx) ** 2 + (ny - cy) ** 2, axis=1)
        rows = np.arange(len(best))
        qx[s:s + chunk], qy[s:s + chunk] = nx[rows, best], ny[rows, best]
    return qx, qy


def _shift(array, dy, dx, fill):
    out = np.full_like(array, fill)
    h, w = array.shape
    out[max(dy, 0):h + min(dy, 0), max(dx, 0):w + min(dx, 0)] = \
        array[max(-dy, 0):h + min(-dy, 0), max(-dx, 0):w + min(-dx, 0)]
    return out


def signed_distance(rings, inside, xs, ys):
    """Distancia euclídea con signo a la costa (+ tierra, − agua).

    Siembra puntos exactos sobre los segmentos en las celdas frontera y los
    propaga con Jump Flooding: precisión sub-celda en O(N² log N), sin SciPy.
    """
    grid_x, grid_y = np.meshgrid(xs, ys)
    edge = np.zeros_like(inside)
    edge[:, 1:] |= inside[:, 1:] != inside[:, :-1]
    edge[:, :-1] |= inside[:, :-1] != inside[:, 1:]
    edge[1:, :] |= inside[1:, :] != inside[:-1, :]
    edge[:-1, :] |= inside[:-1, :] != inside[1:, :]
    rows, cols = np.nonzero(edge)
    seed_x, seed_y = np.full(inside.shape, np.inf), np.full(inside.shape, np.inf)
    seed_x[rows, cols], seed_y[rows, cols] = _nearest_points_on_segments(
        grid_x[rows, cols], grid_y[rows, cols], *ring_segments(rings))
    best = (grid_x - seed_x) ** 2 + (grid_y - seed_y) ** 2

    step = 1 << int(math.log2(max(inside.shape)))
    steps = []
    while step >= 1:
        steps.append(step)
        step //= 2
    for step in steps + [1]:
        for dy in (-step, 0, step):
            for dx in (-step, 0, step):
                if dx == 0 and dy == 0:
                    continue
                cand_x, cand_y = _shift(seed_x, dy, dx, np.inf), _shift(seed_y, dy, dx, np.inf)
                dist2 = (grid_x - cand_x) ** 2 + (grid_y - cand_y) ** 2
                better = dist2 < best
                seed_x[better], seed_y[better], best[better] = cand_x[better], cand_y[better], dist2[better]
    distance = np.sqrt(best)
    return np.where(inside, distance, -distance)


def _box_blur_axis(array, radius, axis):
    pad = [(0, 0), (0, 0)]
    pad[axis] = (radius + 1, radius)
    csum = np.cumsum(np.pad(array, pad, mode="edge"), axis=axis)
    n = array.shape[axis]
    upper = np.take(csum, np.arange(2 * radius + 1, 2 * radius + 1 + n), axis=axis)
    lower = np.take(csum, np.arange(n), axis=axis)
    return (upper - lower) / (2 * radius + 1)


def gaussian_blur(array, sigma, cell):
    """Gaussiana aproximada con 3 pasadas de caja (sigma en unidades de mapa)."""
    sigma_cells = sigma / cell
    radius = int(round((math.sqrt(4.0 * sigma_cells ** 2 + 1.0) - 1.0) / 2.0))
    out = array.astype(np.float64)
    if radius < 1:
        return out
    for _ in range(3):
        out = _box_blur_axis(_box_blur_axis(out, radius, 0), radius, 1)
    return out


def distance_to_polyline(grid_x, grid_y, points):
    distance = np.full(grid_x.shape, np.inf)
    for (ax, ay), (bx, by) in zip(points, points[1:]):
        dx, dy = bx - ax, by - ay
        t = np.clip(((grid_x - ax) * dx + (grid_y - ay) * dy) / (dx * dx + dy * dy), 0.0, 1.0)
        distance = np.minimum(distance, np.hypot(grid_x - (ax + t * dx), grid_y - (ay + t * dy)))
    return distance


def sample_grid(grid, xs, ys, x, y):
    """Interpolación bilineal de una rejilla regular en (x, y)."""
    fx = float(np.interp(x, xs, np.arange(len(xs))))
    fy = float(np.interp(y, ys, np.arange(len(ys))))
    i, j = min(int(fx), len(xs) - 2), min(int(fy), len(ys) - 2)
    tx, ty = fx - i, fy - j
    return float(grid[j, i] * (1 - tx) * (1 - ty) + grid[j, i + 1] * tx * (1 - ty)
                 + grid[j + 1, i] * (1 - tx) * ty + grid[j + 1, i + 1] * tx * ty)


class Perlin2D:
    """Ruido de gradiente 2D vectorizado (fBm y multifractal de crestas)."""

    def __init__(self, seed, size=256):
        angles = np.random.default_rng(seed).uniform(0.0, 2.0 * np.pi, (size, size))
        self.gx, self.gy, self.mask = np.cos(angles), np.sin(angles), size - 1

    def __call__(self, x, y):
        x0, y0 = np.floor(x), np.floor(y)
        fx, fy = x - x0, y - y0
        ix, iy = x0.astype(np.int64) & self.mask, y0.astype(np.int64) & self.mask
        ix1, iy1 = (ix + 1) & self.mask, (iy + 1) & self.mask

        def corner(row, col, dx, dy):
            return self.gx[row, col] * dx + self.gy[row, col] * dy

        u = fx * fx * fx * (fx * (fx * 6.0 - 15.0) + 10.0)
        v = fy * fy * fy * (fy * (fy * 6.0 - 15.0) + 10.0)
        bottom = corner(iy, ix, fx, fy) + u * (corner(iy, ix1, fx - 1, fy) - corner(iy, ix, fx, fy))
        top = corner(iy1, ix, fx, fy - 1) + u * (corner(iy1, ix1, fx - 1, fy - 1) - corner(iy1, ix, fx, fy - 1))
        return (bottom + v * (top - bottom)) * 1.4142

    def fbm(self, x, y, octaves=5, lacunarity=2.0, gain=0.5):
        total, amplitude, frequency, norm = np.zeros_like(x), 1.0, 1.0, 0.0
        for octave in range(octaves):
            total += amplitude * self(x * frequency + 17.3 * octave, y * frequency - 9.1 * octave)
            norm += amplitude
            amplitude *= gain
            frequency *= lacunarity
        return total / norm

    def ridged(self, x, y, octaves=5, lacunarity=2.1, gain=0.5):
        total, amplitude, frequency, norm = np.zeros_like(x), 1.0, 1.0, 0.0
        for octave in range(octaves):
            total += amplitude * (1.0 - np.abs(self(x * frequency + 5.7 * octave, y * frequency + 3.3 * octave))) ** 2
            norm += amplitude
            amplitude *= gain
            frequency *= lacunarity
        return total / norm


